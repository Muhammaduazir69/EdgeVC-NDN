class Macros:
    def __init__(self):
        self.d = {}

    def set(self, name, fn, fmt="{:.2f}"):
        try:
            v = fn()
            if v is None or (isinstance(v, float) and not np.isfinite(v)):
                raise ValueError
            out = fmt.format(v) if not isinstance(v, str) else v
            # Scientific notation for math mode: 5e-06 -> 5\times10^{-6}
            mt = re.fullmatch(r"(\d(?:\.\d+)?)e([+-])0*(\d+)", out)
            if mt:
                out = r"%s\times10^{%s%s}" % (mt.group(1), "-" if mt.group(2) == "-" else "", mt.group(3))
            self.d[name] = out
        except Exception:
            self.d[name] = "??"

    def write(self, path):
        with open(path, "w") as f:
            f.write("% Generated by paper_analysis/make_macros.py. Do not edit.\n")
            for k in sorted(self.d):
                f.write("\\newcommand{\\%s}{%s}\n" % (k, self.d[k]))


def safe_load(cfg, scen="campus"):
    try:
        return C.load(cfg, scen)
    except SystemExit:
        return None


def mean_of(df, variant, col, **filt):
    if df is None:
        raise ValueError("no data")
    g = df[df.iv_variant == variant]
    for k, v in filt.items():
        g = g[np.isclose(g[k].astype(float), v)]
    return C.ci(g[col].values)[0]


def build_costs(m):
    c = M.costs()
    for name, key in [("costDid", "did_parse_thumbprint"), ("costSig", "interest_sig_verify"),
                      ("costVc", "vc_parse_verify"), ("costPol", "claims_status_policy"),
                      ("costSeal", "rekey_unseal"), ("costSes", "session_lookup"),
                      ("costRe", "pre_reencapsulate"), ("costSign", "decision_sign"),
                      ("costDv", "decision_verify"), ("costPolOnly", "policy_only"), ("costEncap", "pre_encap"),
                      ("costDecap", "pre_decap"), ("costAes", "aes_kib")]:
        m.set(name, lambda key=key: c[key] * 1e6, "{:.1f}" if c[key] * 1e6 >= 1 else "{:.2f}")


