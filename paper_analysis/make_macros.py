"""Single source of truth for every number quoted in the two manuscripts.

Writes manuscripts/paperA_ToN/numbers.tex and manuscripts/paperB_Access/numbers.tex.
Each macro is computed from unrounded data; a missing input yields "??" so that
an incomplete campaign is visible in the PDF instead of a stale number."""
